#!/usr/bin/env node
/**
 * Writes src/components/ui/icon-set.generated.ts: the icons the app's own
 * source names, imported one by one.
 *
 * WHY. `Icon` looks icons up BY NAME (`<Icon name="Check" />`, and names that
 * arrive from data). Looking up through `import * as Icons from "lucide-react"`
 * makes the bundler keep every icon in the library, about 144 kB gzipped, on
 * every page that draws a single one, /join included. A named import of each
 * icon the source actually mentions keeps only those.
 *
 * WHAT COUNTS AS "MENTIONED". Any string literal in src/ that is exactly the
 * name of a lucide icon ("Check", "CalendarX"), anywhere: a prop, a table of
 * names, a ternary. That over-includes a little (a word in a sentence that is
 * also an icon name) and cannot under-include a literal. A name that only
 * exists at run time (an id from the backend, "building-office") is not here;
 * `Icon` hands those to LateIcon, which loads the full set after the page has
 * rendered.
 *
 * Run `npm run build:icons` after adding an icon name; `npm run check:icons`
 * fails when the file is out of date.
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { createRequire } from "node:module";
import { join, relative } from "node:path";

const require = createRequire(import.meta.url);
const root = new URL("..", import.meta.url).pathname;
const OUT = join(root, "src/components/ui/icon-set.generated.ts");

// Not icons, though lucide-react exports them.
const NOT_ICONS = new Set(["Icon", "icons", "createLucideIcon", "LucideProvider", "useLucideContext", "DynamicIcon", "dynamicIconImports"]);

const lucide = require("lucide-react");
const iconNames = new Set(
  Object.keys(lucide).filter((k) => /^[A-Z]/.test(k) && !NOT_ICONS.has(k) && lucide[k] && typeof lucide[k] === "object" && "$$typeof" in lucide[k]),
);

function walk(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) walk(path, out);
    else if (/\.(ts|tsx)$/.test(entry.name) && path !== OUT) out.push(path);
  }
  return out;
}

const used = new Set();
for (const file of walk(join(root, "src"))) {
  const text = readFileSync(file, "utf8");
  for (const m of text.matchAll(/["'`]([A-Z][A-Za-z0-9]*)["'`]/g)) if (iconNames.has(m[1])) used.add(m[1]);
}
const names = [...used].sort();

const body = `// GENERATED by scripts/build-icon-set.mjs (npm run build:icons). Do not edit by hand.
// ${names.length} icons: every string literal in src/ that is the name of a lucide icon.
// Each is imported on its own (as I_<name>, so a name such as Map or Image cannot
// shadow a global) so the bundle holds these and not the whole library.
import {
${names.map((n) => `  ${n} as I_${n},`).join("\n")}
} from "lucide-react";
import type { LucideIcon } from "lucide-react";

export const ICON_SET: ReadonlyMap<string, LucideIcon> = new Map<string, LucideIcon>([
${names.map((n) => `  ["${n}", I_${n}],`).join("\n")}
]);
`;

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== body) {
    const have = new Set([...current.matchAll(/^\s+\["([A-Za-z0-9]+)", I_/gm)].map((m) => m[1]));
    const missing = names.filter((n) => !have.has(n));
    console.error(`icon set is out of date (${relative(root, OUT)}). Missing: ${missing.join(", ") || "(none; extra or reordered entries)"}. Run: npm run build:icons`);
    process.exit(1);
  }
  console.log(`icon set: current (${names.length} icons)`);
} else {
  writeFileSync(OUT, body);
  console.log(`wrote ${relative(root, OUT)} (${names.length} icons)`);
}
